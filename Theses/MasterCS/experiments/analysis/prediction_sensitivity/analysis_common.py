def import_experiment_module(path: str | Path = "run_experiments.py"):
    """Import the original experiment module without executing its main()."""
    path = Path(path)
    if not path.exists():
        raise FileNotFoundError(
            f"Cannot find {path}. Run this script from the directory containing run_experiments.py "
            "or pass --module path/to/run_experiments.py."
        )
    spec = importlib.util.spec_from_file_location("run_experiments_imported", path)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"Cannot import module from {path}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def ensure_extra_dirs(root: str | Path = "outputs/prediction_sensitivity") -> tuple[Path, Path]:
    root = Path(root)
    results = root / "results"
    plots = root / "plots"
    results.mkdir(parents=True, exist_ok=True)
    plots.mkdir(parents=True, exist_ok=True)
    return results, plots


def load_best_parameters(exp, path: str | Path | None = None) -> np.ndarray:
    """Load best_model_parameters.json and return a clipped parameter vector."""
    candidates = []
    if path is not None:
        candidates.append(Path(path))
    candidates.extend([
        Path("experiments/results/best_model_parameters.json"),
        Path("best_model_parameters.json"),
    ])

    for candidate in candidates:
        if candidate.exists():
            payload = json.loads(candidate.read_text(encoding="utf-8"))
            incoming = payload.get("parameters", payload)
            values = exp.with_defaults()
            for name in exp.PARAMETER_NAMES:
                if name in incoming:
                    values[name] = float(incoming[name])
            return exp.clip_candidate(exp.params_dict_to_array(values))

    raise FileNotFoundError(
        "Cannot find best_model_parameters.json. Expected it in experiments/results/ "
        "or pass --best path/to/best_model_parameters.json."
    )


def find_final_cache(exp, path: str | Path | None = None) -> Path:
    """Find the final replay cache generated by run_experiments.py."""
    if path is not None:
        path = Path(path)
        if not path.exists():
            raise FileNotFoundError(path)
        return path

    cache_dir = Path("experiments/cache")
    candidates = sorted(cache_dir.glob("final_*to_*.npz"))
    if not candidates:
        raise FileNotFoundError(
            "No final replay cache found in experiments/cache. "
            "Run: python run_experiments.py --mode evaluate --profile max"
        )

    # Prefer full-history caches over quick caches. Then prefer the newest file.
    full = [p for p in candidates if "fullhistory" in p.name]
    usable = full if full else candidates
    usable.sort(key=lambda p: (p.stat().st_mtime_ns, p.name))
    return usable[-1]


def load_cache(exp, path: str | Path | None = None):
    cache_path = find_final_cache(exp, path)
    cache = exp.load_cache(cache_path)
    print(f"[CACHE] using {cache_path}")
    print(f"[CACHE] games={cache.games:,}, players={cache.players:,}, pools={cache.pools:,}")
    return cache


def safe_mse(error_sum: float, count: int) -> float:
    return float(error_sum / count) if int(count) > 0 else float("nan")


def output_scope_records(exp, cache, model_name: str, parameters: np.ndarray, output) -> list[dict[str, object]]:
    squared_error, absolute_error, counts, shared_error, shared_counts, fide_error, fide_counts = output[:7]
    records = []
    for scope_code in (1, 2, 3):
        count = int(counts[scope_code])
        shared_count = int(shared_counts[scope_code])
        fide_count = int(fide_counts[scope_code])
        records.append({
            "model": model_name,
            "scope": exp.scope_name(scope_code),
            "games_all": count,
            "mse_all": safe_mse(float(squared_error[scope_code]), count),
            "mae_all": float(absolute_error[scope_code] / count) if count else float("nan"),
            "games_shared_with_fide": shared_count,
            "mse_shared_with_fide": safe_mse(float(shared_error[scope_code]), shared_count),
            "fide_official_mse_on_shared": safe_mse(float(fide_error[scope_code]), fide_count),
        })
    return records


def output_monthly_records(exp, cache, model_name: str, output) -> list[dict[str, object]]:
    monthly_squared_error = output[9]
    monthly_count = output[10]
    monthly_shared_error = output[11]
    monthly_shared_count = output[12]
    monthly_fide_error = output[13]
    monthly_fide_count = output[14]

    rows = []
    for i in range(len(monthly_count)):
        count = int(monthly_count[i])
        if count <= 0:
            continue
        month_index = cache.first_month_index + i
        rows.append({
            "model": model_name,
            "month": exp.index_to_month(month_index),
            "games_all": count,
            "mse_all": safe_mse(float(monthly_squared_error[i]), count),
            "games_shared_with_fide": int(monthly_shared_count[i]),
            "mse_shared_with_fide": safe_mse(float(monthly_shared_error[i]), int(monthly_shared_count[i])),
            "fide_official_mse_on_shared": safe_mse(float(monthly_fide_error[i]), int(monthly_fide_count[i])),
        })
    return rows


def evaluate_model(exp, cache, model_name: str, parameters: np.ndarray, *, monthly: bool = False):
    parameters = exp.clip_candidate(parameters)
    output = exp.evaluate_candidate(cache, parameters, collect_monthly=monthly, collect_rating_ranges=False)
    scope = pd.DataFrame(output_scope_records(exp, cache, model_name, parameters, output))
    monthly_df = pd.DataFrame(output_monthly_records(exp, cache, model_name, output)) if monthly else pd.DataFrame()
    return scope, monthly_df, output


def add_improvement_vs_baseline(df: pd.DataFrame, baseline_model: str = "classic_elo") -> pd.DataFrame:
    df = df.copy()
    baseline = df[df["model"] == baseline_model][["scope", "mse_all"]].rename(columns={"mse_all": "baseline_mse"})
    if baseline.empty:
        return df
    df = df.merge(baseline, on="scope", how="left")
    df["improvement_vs_baseline_percent"] = (df["baseline_mse"] - df["mse_all"]) / df["baseline_mse"] * 100.0
    return df


def parse_float_list(text: str) -> list[float]:
    return [float(x.strip()) for x in text.split(",") if x.strip()]


def parse_int_list(text: str) -> list[int]:
    return [int(x.strip()) for x in text.split(",") if x.strip()]


def expected_points(diff: np.ndarray | float, scale: np.ndarray | float) -> np.ndarray | float:
    exponent = -np.asarray(diff) / np.asarray(scale)
    exponent = np.clip(exponent, -20.0, 20.0)
    return 1.0 / (1.0 + np.power(10.0, exponent))


def month_to_index(value: str) -> int:
    year, month = value.split("-")[:2]
    return int(year) * 12 + int(month) - 1
